"""Build NarewStudio.exe + NarewModManager.exe (windowed) + NarewAgent.exe (console: MCP server / CLI for
AI agents), sharing one Qt runtime, with PyInstaller.

    python tools/build_exe.py            -> dist/NarewTools/{NarewStudio,NarewModManager,NarewAgent}.exe
                                            dist/NarewTools-<version>.zip (to share)
                                            dist/NarewTools-<version>.zip.sha256 (for the self-update)

All programs go into one folder so the large Qt / OpenGL libraries are stored once.  After the
build each exe runs its self test (Studio also starts OpenGL; the agent answers an MCP handshake and
puts a fake update into a scratch folder) before the zip is made.  A GitHub release gets both the zip
and the .sha256 file as assets (tag v<version>): the programs' self-update looks for exactly those names.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import zipfile

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from narew.version import VERSION  # noqa: E402

BUILD = os.path.join(ROOT, 'build')
DIST = os.path.join(ROOT, 'dist')
NAME = 'NarewTools'

APPS = [
    # exe name, entry module (with main(argv)), icon letter, colour, console
    ('NarewStudio', 'studio.app', 'N', (61, 138, 73), False),
    ('NarewModManager', 'modmanager.app', 'M', (52, 110, 170), False),
    ('NarewAgent', 'studio.agent.cli', 'A', (150, 90, 170), True),
]

# Qt modules the tools never import (keeps the folder ~half the size)
QT_EXCLUDES = ['Qt3DAnimation', 'Qt3DCore', 'Qt3DExtras', 'Qt3DInput', 'Qt3DLogic', 'Qt3DRender', 'QtBluetooth',
               'QtCharts', 'QtConcurrent', 'QtDataVisualization', 'QtDesigner', 'QtGraphs', 'QtHelp', 'QtHttpServer',
               'QtLocation', 'QtNetworkAuth', 'QtNfc', 'QtPdf', 'QtPdfWidgets', 'QtPositioning', 'QtQml', 'QtQuick',
               'QtQuick3D', 'QtQuickControls2', 'QtQuickWidgets', 'QtRemoteObjects', 'QtScxml', 'QtSensors',
               'QtSerialBus', 'QtSerialPort', 'QtSpatialAudio', 'QtSql', 'QtStateMachine', 'QtTest',
               'QtTextToSpeech', 'QtUiTools', 'QtWebChannel', 'QtWebEngineCore', 'QtWebEngineQuick',
               'QtWebEngineWidgets', 'QtWebSockets', 'QtWebView', 'QtXml']
EXCLUDES = ['tkinter', 'matplotlib', 'scipy', 'pandas', 'webview', 'IPython', 'pytest'] + \
           [f'PySide6.{m}' for m in QT_EXCLUDES]

SPEC = '''# generated by tools/build_exe.py
from PyInstaller.utils.hooks import collect_submodules

ROOT = {root!r}
EXCLUDES = {excludes!r}
HIDDEN = collect_submodules('glcontext') + collect_submodules('studio') + collect_submodules('modmanager') \\
    + collect_submodules('narew')
apps = {apps!r}
built = []
for name, package, entry, icon, console in apps:
    a = Analysis([entry], pathex=[ROOT], hiddenimports=HIDDEN, excludes=EXCLUDES, noarchive=False)
    exe = EXE(PYZ(a.pure), a.scripts, [], exclude_binaries=True, name=name, icon=icon, console=console,
              upx=False, version=None)
    built += [exe, a.binaries, a.datas]
coll = COLLECT(*built, upx=False, name={name!r})
'''


def make_icon(path: str, letter: str, color):
    size = 256
    im = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((8, 8, size - 8, size - 8), radius=48, fill=color + (255,))
    try:
        font = ImageFont.truetype('segoeuib.ttf', 170)
    except OSError:
        font = ImageFont.load_default()
    box = d.textbbox((0, 0), letter, font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    d.text(((size - w) / 2 - box[0], (size - h) / 2 - box[1]), letter, font=font, fill=(255, 255, 255, 255))
    im.save(path, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


def write_spec() -> str:
    os.makedirs(BUILD, exist_ok=True)
    apps = []
    for name, module, letter, color, console in APPS:
        package = module.replace('.', '_')
        entry = os.path.join(BUILD, f'entry_{package}.py')
        with open(entry, 'w', encoding='utf-8') as f:
            f.write(f'import sys\nfrom {module} import main\nsys.exit(main(sys.argv[1:]))\n')
        icon = os.path.join(BUILD, f'{package}.ico')
        make_icon(icon, letter, color)
        apps.append((name, package, entry, icon, console))
    spec = os.path.join(BUILD, f'{NAME}.spec')
    with open(spec, 'w', encoding='utf-8') as f:
        f.write(SPEC.format(root=ROOT, excludes=EXCLUDES, apps=apps, name=NAME))
    return spec


def selftest(folder: str):
    env = dict(os.environ)
    scratch = os.path.join(BUILD, 'selftest')
    shutil.rmtree(scratch, ignore_errors=True)
    os.makedirs(scratch)
    env['APPDATA'] = env['LOCALAPPDATA'] = scratch       # do not touch the user's settings
    for name, *_, console in APPS:
        exe = os.path.join(folder, name + '.exe')
        if console:                                    # the agent: one MCP handshake + tools/list
            req = (b'{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18"}}\n'
                   b'{"jsonrpc":"2.0","id":2,"method":"tools/list"}\n')
            r = subprocess.run([exe, 'mcp'], env=env, input=req, capture_output=True, timeout=180)
            ok = r.returncode == 0 and b'"narew-studio"' in r.stdout and b'world_fill' in r.stdout
            print(f'{name}: mcp {"OK" if ok else "FAILED"}')
            if not ok:
                raise SystemExit(f'{name} selftest failed:\n{r.stdout[-2000:]!r}\n{r.stderr[-2000:]!r}')
            update_selftest(exe, env, scratch)
            continue
        # windowed exes have no console: the log file under the scratch APPDATA gets the output
        r = subprocess.run([exe, '--selftest'], env=env, timeout=180)
        logs = [os.path.join(d, 'log.txt') for d in (os.path.join(scratch, 'NarewStudio'),
                                                    os.path.join(scratch, 'NarewModManager'))]
        text = ''.join(open(p, encoding='utf-8').read() for p in logs if os.path.isfile(p))
        print(f'{name}: exit {r.returncode}', text.strip().splitlines()[-1:] if text else '')
        if r.returncode != 0:
            raise SystemExit(f'{name} selftest failed:\n{text}')


def update_selftest(agent: str, env: dict, scratch: str):
    """The built agent puts a fake update into a scratch 'install' folder, as the self-update runs it
    (NarewAgent.exe --apply-update <job.json>): files replaced, the old ones backed up."""
    inst, new = os.path.join(scratch, 'install'), os.path.join(scratch, 'staged')
    for d, text in ((inst, 'old'), (new, 'new')):
        os.makedirs(os.path.join(d, 'sub'))
        for p in ('NarewStudio.exe', 'NarewModManager.exe', 'NarewAgent.exe', os.path.join('sub', 'f.txt')):
            with open(os.path.join(d, p), 'w') as f:
                f.write(text)
    job = {'version': '0.0.1', 'old_version': '0.0.0', 'staged': new, 'install': inst, 'pid': 0, 'restart': None,
           'backup': os.path.join(scratch, 'backup'), 'log': os.path.join(scratch, 'update.log')}
    path = os.path.join(scratch, 'job.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(job, f)
    r = subprocess.run([agent, '--apply-update', path], env=env, capture_output=True, timeout=300)

    def read(*p):
        with open(os.path.join(*p)) as f:
            return f.read()
    ok = r.returncode == 0 and read(inst, 'sub', 'f.txt') == 'new' and read(scratch, 'backup', 'sub', 'f.txt') == 'old'
    print(f'{os.path.basename(agent)}: apply-update {"OK" if ok else "FAILED"}')
    if not ok:
        log = read(scratch, 'update.log') if os.path.isfile(os.path.join(scratch, 'update.log')) else ''
        raise SystemExit(f'update selftest failed (exit {r.returncode}):\n{log}\n{r.stderr[-2000:]!r}')


def write_sha256(path: str) -> str:
    """<zip>.sha256 = "<hex>  <name>" (the release asset the self-update checks the download with)."""
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    out = path + '.sha256'
    with open(out, 'w', encoding='ascii', newline='\n') as f:
        f.write(f'{h.hexdigest()}  {os.path.basename(path)}\n')
    return out


def make_zip(folder: str) -> str:
    out = os.path.join(os.path.dirname(folder), f'{NAME}-{VERSION}.zip')
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for d, _, files in os.walk(folder):
            for fn in files:
                full = os.path.join(d, fn)
                z.write(full, os.path.join(NAME, os.path.relpath(full, folder)))
        readme = os.path.join(ROOT, 'docs', 'USER-GUIDE.txt')
        if os.path.isfile(readme):
            z.write(readme, os.path.join(NAME, '사용법.txt'))
    return out


def main():
    # --dist DIR: build somewhere else (e.g. while dist\NarewTools is in use)
    dist = sys.argv[sys.argv.index('--dist') + 1] if '--dist' in sys.argv else DIST
    spec = write_spec()
    cmd = [sys.executable, '-m', 'PyInstaller', '--noconfirm', '--clean', '--distpath', dist,
           '--workpath', os.path.join(BUILD, 'work'), spec]
    print(' '.join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=ROOT)
    folder = os.path.join(dist, NAME)
    selftest(folder)
    size = sum(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(folder) for f in fs)
    print(f'folder: {folder} ({size / 2 ** 20:.0f} MB)')
    z = make_zip(folder)
    print('zip:', z)
    print('sha256:', write_sha256(z))


if __name__ == '__main__':
    main()
